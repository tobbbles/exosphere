defmodule Exospace.Interop.SpacesCorpusTest do
  @moduledoc """
  Conformance against the counterparty corpus: bytes generated by the official
  reference implementation of proposal 0016 (`@atproto/space` and
  `@atproto/star`, MIT, pinned at atproto `atproto-spaces-cleanup` `4037310`
  with `@atproto/star` from `permissioned-data` `98ef3a6`). See
  `test/fixtures/spaces-corpora/SOURCE.md` for provenance and how to
  regenerate.

  This is the G1 gate's strongest evidence — the two implementations were
  written independently and must agree on the exact bytes: LtHash states and
  digests, the KEM shared secrets (RFC 9180 DHKEM(P-256)), the commit and
  record MACs and the headers carrying them, the `atproto-space-repo` STAR
  archive, the token classes, and the HTTP message signature that presents a
  credential. A failure here is either a spec-reading bug in exosphere or a
  reference divergence from the proposal text — both are findings, never
  silently reconciled.
  """

  use ExUnit.Case, async: true

  alias Exosphere.ATProto.{CID, Star}
  alias Exosphere.ATProto.Spaces.{Commit, HttpSignature, Kem, Lthash, Mac, Repo, Token}
  alias Exosphere.Test.Interop

  defp unhex(s), do: Base.decode16!(s, case: :mixed)

  @lthash Interop.spaces_corpus("lthash.json")
  @commit_mac Interop.spaces_corpus("commit-mac.json")
  @repo_star Interop.spaces_corpus("repo-star.json")
  @credentials Interop.spaces_corpus("credentials.json")

  describe "lthash: the corpus digests reproduce exactly" do
    test "every case folds to the reference state and digest" do
      for case <- @lthash["cases"] do
        hash =
          Enum.reduce(case["ops"], Lthash.new(), fn %{"op" => op, "element" => element}, acc ->
            apply(Lthash, String.to_existing_atom(op), [acc, element])
          end)

        assert Lthash.state(hash) == Base.decode64!(case["state"]),
               "#{case["name"]}: state diverged"

        assert Base.encode16(Lthash.digest(hash), case: :lower) == case["digest"],
               "#{case["name"]}: digest diverged"

        assert Lthash.empty?(hash) == case["isEmpty"], "#{case["name"]}: emptiness diverged"
      end
    end

    test "the reference's noble test elements match the snapshot vectors" do
      # Cross-tie with lthash_test's hand-pinned digests: same bytes, second source.
      one_two =
        Enum.find(@lthash["cases"], &(&1["name"] == "noble-elements-one-two"))

      assert one_two["digest"] ==
               String.downcase("AE05CB6D224379D9710C290C8529945C5B0E0FDE9EAD30B9699057CE701C63E7")

      empty = Enum.find(@lthash["cases"], &(&1["name"] == "empty"))

      assert empty["digest"] ==
               String.downcase("E5A00AA9991AC8A5EE3109844D84A55583BD20572AD3FFCD42792F3C36B183AD")
    end

    test "add-remove cycles and multiset underflow behave homomorphically" do
      returns = Enum.find(@lthash["cases"], &(&1["name"] == "add-remove-returns-to-empty"))
      assert returns["isEmpty"] == true
      assert returns["state"] == Base.encode64(:binary.copy(<<0>>, 2048))

      # A remove that underflows past zero wraps mod 2^16 and is undone by the
      # matching add: the reference pins that, not a clamp at zero.
      underflow =
        Enum.find(@lthash["cases"], &(&1["name"] == "remove-before-add-underflows-to-same-state"))

      assert underflow["isEmpty"] == true

      multiset = Enum.find(@lthash["cases"], &(&1["name"] == "multiset-double-add-single-remove"))
      assert multiset["isEmpty"] == false
      single = Enum.find(@lthash["cases"], &(&1["name"] == "single-record-element"))
      assert multiset["state"] == single["state"]
    end
  end

  describe "KEM: the reference's shared secrets reproduce exactly" do
    test "decapsulate/2 and a pinned encapsulate/2 derive every recorded secret" do
      author = @commit_mac["kem"]["author"]
      author_priv = unhex(author["privateKey"])

      for vector <- @commit_mac["kem"]["vectors"] do
        secret = unhex(vector["sharedSecret"])

        assert {:ok, ^secret} = Kem.decapsulate(author_priv, vector["keyShare"])

        assert {:ok, %{key_share: key_share, shared_secret: ^secret}} =
                 Kem.encapsulate(author["didKey"],
                   ephemeral_private_key: unhex(vector["ephemeralPrivateKey"])
                 )

        assert key_share == vector["keyShare"]
      end
    end
  end

  describe "commit and record MACs, and their headers, byte-for-byte" do
    test "every commit's data, MAC and headers match the reference" do
      for variant <- @commit_mac["commits"] do
        %{"space" => space, "repo" => repo, "rev" => rev} = variant["ctx"]
        secret = unhex(variant["sharedSecret"])

        hash = Enum.reduce(variant["elements"], Lthash.new(), &Lthash.add(&2, &1))
        commit = Commit.build(hash, %{space: space, repo: repo, rev: rev})

        assert commit == wire_commit(variant["commit"]), "#{variant["name"]}: commit diverged"

        mac = Commit.mac(commit, secret)
        assert mac == unhex(variant["mac"]), "#{variant["name"]}: MAC diverged"
        assert Mac.mac_header(:commit, mac) == variant["macHeader"]

        key_share = Enum.at(@commit_mac["kem"]["vectors"], variant["kemVector"])["keyShare"]
        assert Mac.want_mac_header(:commit, key_share) == variant["wantMacHeader"]

        assert {:ok, ^mac} = Mac.parse_mac_header(variant["macHeader"], :commit)
        assert :ok = Commit.verify(commit, %{space: space, repo: repo}, secret, mac)
      end
    end

    test "a tampered field fails the reference's MAC" do
      variant = hd(@commit_mac["commits"])
      commit = wire_commit(variant["commit"])
      ctx = %{space: commit["space"], repo: commit["repo"]}
      secret = unhex(variant["sharedSecret"])
      mac = unhex(variant["mac"])

      assert {:error, :invalid_mac} =
               Commit.verify(%{commit | "rev" => "3kbcq3p7ad2c3"}, ctx, secret, mac)

      assert {:error, :invalid_mac} =
               Commit.verify(%{commit | "data" => :crypto.hash(:sha256, "x")}, ctx, secret, mac)
    end

    test "every record MAC and header matches, over the value's own CID" do
      for variant <- @commit_mac["records"] do
        vector = Enum.at(@commit_mac["kem"]["vectors"], variant["kemVector"])
        secret = unhex(vector["sharedSecret"])
        cid = CID.create!(variant["value"])

        assert CID.encode(cid) == variant["cid"]
        assert CID.to_bytes(cid) == unhex(variant["cidBytes"])

        mac = Mac.record_mac(secret, variant["uri"], CID.to_bytes(cid))
        assert mac == unhex(variant["mac"]), "#{variant["name"]}: record MAC diverged"
        assert Mac.mac_header(:record, mac) == variant["macHeader"]
        assert Mac.want_mac_header(:record, vector["keyShare"]) == variant["wantMacHeader"]
      end
    end
  end

  describe "repo STAR: layout, key order, and byte-identical serialization" do
    setup do
      records =
        Enum.map(@repo_star["records"], fn r -> {r["collection"], r["rkey"], r["record"]} end)

      secret =
        unhex(Enum.at(@commit_mac["kem"]["vectors"], @repo_star["kemVector"])["sharedSecret"])

      %{
        records: records,
        commit: wire_commit(@repo_star["commit"]),
        star: Base.decode64!(@repo_star["star"]),
        secret: secret,
        ctx: %{space: @repo_star["ctx"]["space"], repo: @repo_star["ctx"]["repo"]}
      }
    end

    test "serialize/2 reproduces the reference archive byte-for-byte", ctx do
      assert Repo.serialize(ctx.commit, ctx.records) == ctx.star
    end

    test "verify/4 accepts the reference archive end to end", ctx do
      assert {:ok, verified} =
               Repo.verify(ctx.star, ctx.ctx, ctx.secret, unhex(@repo_star["mac"]))

      assert Enum.map(verified.records, &"#{&1.collection}/#{&1.rkey}") ==
               Enum.map(@repo_star["pairs"], & &1["key"])

      assert Commit.matches?(verified.lthash, ctx.commit)
    end

    test "the pairs are in strict key-byte order, not length-first", ctx do
      keys = Enum.map(@repo_star["pairs"], & &1["key"])
      assert keys == Enum.sort(keys)
      # The pair that tells the rules apart: bytewise, a.foo.bar sorts first.
      assert hd(keys) == "a.foo.bar/abcdefgh"
      assert List.last(keys) == "z.foo.bar/a"

      {:ok, %{pairs: pairs}} = Star.decode(ctx.star)

      assert Enum.map(pairs, fn {k, v} -> %{"key" => k, "value" => hex(v)} end) ==
               @repo_star["pairs"]
    end

    test "the empty repo archive round-trips too" do
      empty = @repo_star["empty"]
      commit = wire_commit(empty["commit"])
      star = Base.decode64!(empty["star"])
      assert Repo.serialize(commit, []) == star

      secret = unhex(hd(@commit_mac["kem"]["vectors"])["sharedSecret"])

      assert {:ok, %{records: []}} =
               Repo.verify(
                 star,
                 %{space: commit["space"], repo: commit["repo"]},
                 secret,
                 unhex(empty["mac"])
               )
    end

    test "a tampered record fails the digest", ctx do
      [first | rest] = ctx.records
      {c, r, rec} = first
      tampered = Repo.serialize(ctx.commit, [{c, r, Map.put(rec, "extra", 1)} | rest])

      assert {:error, :records_do_not_match_commit} =
               Repo.verify(tampered, ctx.ctx, ctx.secret, unhex(@repo_star["mac"]))
    end
  end

  describe "credential token classes (shape + signature, not bytes)" do
    test "each class parses and verifies against its recorded signing key" do
      for token <- @credentials["tokens"] do
        class = token_class(token["class"])
        expected = token["expected"]

        assert {:ok, %{header: header, payload: payload}} = Token.parse(class, token["jwt"])

        # The reference's own decoded header, verbatim.
        assert header == Map.new(token["header"])

        if expected["kid"], do: assert(header["kid"] == expected["kid"])
        if expected["noKid"], do: refute(Map.has_key?(header, "kid"))

        assert payload["iss"] == expected["iss"]
        assert payload["sub"] == expected["sub"]
        assert payload["exp"] - payload["iat"] == expected["expMinusIat"]
        assert is_binary(payload["jti"]) and payload["jti"] != ""

        if expected["aud"], do: assert(payload["aud"] == expected["aud"])
        if expected["noAud"], do: refute(Map.has_key?(payload, "aud"))
        if expected["cnfKid"], do: assert(payload["cnf"] == %{"kid" => expected["cnfKid"]})

        # The audience the reference addresses (spaceHostAud) is ours too.
        if expected["aud"],
          do: assert(expected["aud"] == Token.space_host_aud("did:plc:spaceauthority"))

        # Signature validity, checked just after minting (the fixture's iat).
        jwk = token["signingKey"]["jwk"]

        assert {:ok, _} =
                 Token.verify(class, token["jwt"],
                   now: payload["iat"] + 10,
                   get_signing_key: fn _iss, _kid, _refresh -> {:ok, jwk} end
                 )
      end
    end

    test "a delegation token checked well past expiry fails verification" do
      token = Enum.find(@credentials["tokens"], &(&1["class"] == "delegation"))
      {:ok, %{payload: payload}} = Token.parse(:delegation, token["jwt"])
      jwk = token["signingKey"]["jwk"]

      assert {:error, :token_expired} =
               Token.verify(:delegation, token["jwt"],
                 now: payload["exp"] + 60,
                 get_signing_key: fn _, _, _ -> {:ok, jwk} end
               )
    end
  end

  describe "the HTTP message signature that presents a credential" do
    test "the reference's signature verifies against the bound key" do
      sig = @credentials["httpSignature"]
      assert :ok = HttpSignature.verify(Map.to_list(sig["headers"]), sig["key"]["didKey"])
    end

    test "exosphere signs the same covered components, input and base" do
      sig = @credentials["httpSignature"]
      {:ok, key} = HttpSignature.key_from_private(unhex(sig["key"]["privateKey"]))
      assert key.did_key == sig["key"]["didKey"]

      "Atproto-Space-Credential " <> jwt = sig["authorization"]
      {:ok, headers} = HttpSignature.headers(key, jwt, sig["audience"])

      # Everything but the signature value (P-256 here signs with a random
      # nonce, the reference with RFC 6979) is byte-identical...
      for name <- ["authorization", "atproto-space-audience", "signature-input"] do
        assert {^name, value} = List.keyfind(headers, name, 0)
        assert value == sig["headers"][name], "#{name} diverged"
      end

      # ...and the signature verifies under the same check the reference's does.
      assert :ok = HttpSignature.verify(headers, key.did_key)
    end
  end

  defp wire_commit(%{} = commit), do: Map.update!(commit, "data", &unhex/1)
  defp hex(bytes), do: Base.encode16(bytes, case: :lower)

  defp token_class("delegation"), do: :delegation
  defp token_class("credential"), do: :credential
  defp token_class("clientAttestation"), do: :client_attestation
end
