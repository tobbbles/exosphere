defmodule Exospace.Interop.SpacesCorpusTest do
  @moduledoc """
  Conformance against the counterparty corpus: bytes generated by the official
  reference implementation of proposal 0016 (`@atproto/space`, MIT, pinned at
  atproto `787a730`). See `test/fixtures/spaces-corpora/SOURCE.md` for
  provenance and how to regenerate.

  This is the G1 gate's strongest evidence — the two implementations were
  written independently and must agree on the exact bytes: LtHash states and
  digests, the commit context encoding, the HKDF-Expand-only MAC, the
  deterministic secp256k1 signature (RFC 6979 on both sides), and the whole
  two-root CAR. A failure here is either a spec-reading bug in exosphere or a
  reference divergence from the proposal text — both are findings, never
  silently reconciled.
  """

  use ExUnit.Case, async: true

  alias Exosphere.ATProto.Spaces.{Lthash, Token}
  alias Exosphere.Test.Interop

  @lthash Interop.spaces_corpus("lthash.json")
  @credentials Interop.spaces_corpus("credentials.json")

  describe "lthash: the corpus digests reproduce exactly" do
    test "every case folds to the reference state and digest" do
      for case <- @lthash["cases"] do
        hash =
          Enum.reduce(case["ops"], Lthash.new(), fn %{"op" => op, "element" => element}, acc ->
            apply(Lthash, String.to_existing_atom(op), [acc, element])
          end)

        assert Lthash.state(hash) == Base.decode64!(case["state"]),
               "#{case["name"]}: state diverged"

        assert Base.encode16(Lthash.digest(hash), case: :lower) == case["digest"],
               "#{case["name"]}: digest diverged"

        assert Lthash.empty?(hash) == case["isEmpty"], "#{case["name"]}: emptiness diverged"
      end
    end

    test "the reference's noble test elements match the snapshot vectors" do
      # Cross-tie with lthash_test's hand-pinned digests: same bytes, second source.
      one_two =
        Enum.find(@lthash["cases"], &(&1["name"] == "noble-elements-one-two"))

      assert one_two["digest"] ==
               String.downcase("AE05CB6D224379D9710C290C8529945C5B0E0FDE9EAD30B9699057CE701C63E7")

      empty = Enum.find(@lthash["cases"], &(&1["name"] == "empty"))

      assert empty["digest"] ==
               String.downcase("E5A00AA9991AC8A5EE3109844D84A55583BD20572AD3FFCD42792F3C36B183AD")
    end

    test "add-remove cycles and multiset underflow behave homomorphically" do
      returns = Enum.find(@lthash["cases"], &(&1["name"] == "add-remove-returns-to-empty"))
      assert returns["isEmpty"] == true
      assert returns["state"] == Base.encode64(:binary.copy(<<0>>, 2048))

      # A remove that underflows past zero wraps mod 2^16 and is undone by the
      # matching add: the reference pins that, not a clamp at zero.
      underflow =
        Enum.find(@lthash["cases"], &(&1["name"] == "remove-before-add-underflows-to-same-state"))

      assert underflow["isEmpty"] == true

      multiset = Enum.find(@lthash["cases"], &(&1["name"] == "multiset-double-add-single-remove"))
      assert multiset["isEmpty"] == false
      single = Enum.find(@lthash["cases"], &(&1["name"] == "single-record-element"))
      assert multiset["state"] == single["state"]
    end
  end

  describe "credential token classes (shape + signature, not bytes)" do
    # The pinned fixture (atproto 787a730) predates the cnf.kid binding and the
    # 600s credential; re-pinned when the corpus is regenerated at 98ef3a6.
    @describetag skip: "corpus predates cnf.kid (b34848587); regenerated later in this series"

    test "each class parses and verifies against its recorded signing key" do
      for token <- @credentials["tokens"] do
        class = token_class(token["class"])
        expected = token["expected"]

        assert {:ok, %{header: header, payload: payload}} = Token.parse(class, token["jwt"])

        # The reference's own decoded header, verbatim.
        assert header == Map.new(token["header"])

        if expected["kid"], do: assert(header["kid"] == expected["kid"])
        if expected["noKid"], do: refute(Map.has_key?(header, "kid"))

        assert payload["iss"] == expected["iss"]
        assert payload["sub"] == expected["sub"]
        assert payload["exp"] - payload["iat"] == expected["expMinusIat"]

        if expected["aud"], do: assert(payload["aud"] == expected["aud"])
        if expected["noAud"], do: refute(Map.has_key?(payload, "aud"))
        if expected["cnfJkt"], do: assert(payload["cnf"]["jkt"] == expected["cnfJkt"])

        # Signature validity, checked just after minting (the fixture's iat).
        jwk = token["signingKey"]["jwk"]

        assert {:ok, _} =
                 Token.verify(class, token["jwt"],
                   now: payload["iat"] + 10,
                   get_signing_key: fn _iss, _kid, _refresh -> {:ok, jwk} end
                 )
      end
    end

    test "a delegation token checked well past expiry fails verification" do
      token = Enum.find(@credentials["tokens"], &(&1["class"] == "delegation"))
      {:ok, %{payload: payload}} = Token.parse(:delegation, token["jwt"])
      jwk = token["signingKey"]["jwk"]

      assert {:error, :token_expired} =
               Token.verify(:delegation, token["jwt"],
                 now: payload["exp"] + 60,
                 get_signing_key: fn _, _, _ -> {:ok, jwk} end
               )
    end
  end

  defp token_class("delegation"), do: :delegation
  defp token_class("credential"), do: :credential
  defp token_class("clientAttestation"), do: :client_attestation
end
